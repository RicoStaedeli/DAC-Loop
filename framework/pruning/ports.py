# ports.py
from typing import Protocol, Iterable, Tuple, Optional
import torch
import torch.nn as nn

class PruningStrategy(Protocol):
    def prepare(self, model: nn.Module) -> None: ...
    def apply(self, model: nn.Module) -> None: ...
    def finalize(self, model: nn.Module) -> None: ...

class SparsityReporter(Protocol):
    def layerwise(self, model: nn.Module) -> Iterable[Tuple[str, float]]: ...
    def overall(self, model: nn.Module) -> float: ...

class Surgeon(Protocol):
    def build(self, model: nn.Module, example_input: torch.Tensor) -> None: ...
    def prune_channels(self, model: nn.Module, layer_prune_ratio: float, min_channels: int) -> None: ...
    def clean(self, model: nn.Module) -> None: ...